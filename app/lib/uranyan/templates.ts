// ─────────────────────────────────────────────────────────────
// 公開: 天命トリセツ全体
// ─────────────────────────────────────────────────────────────
export interface PillarReading {
  label: string         // "外キャラ" など UI 表示用
  star: MainStar        // 該当する十大主星
  starHeadline: string  // "頑固なマイペース" など短いヘッドライン
  main: CharLine        // 主軸セリフ
}

export interface LifeReading {
  outer: PillarReading
  middle: PillarReading
  inner: PillarReading
  luckyColor: { name: string; hex: string }
  bucchakeLevel: number  // 1..5
  sanchu: Sanchu         // 元データ (デバッグ表示や共有用)
  stars: ThreeStars
}

export function buildLifeReading(birth: { year: number; month: number; day: number }): LifeReading {
  const sanchu = calcSanchu(birth.year, birth.month, birth.day)
  const stars = deriveThreeStars(sanchu)
  return {
    outer: {
      label: '外キャラ',
      star: stars.north,
      starHeadline: STAR_HEADLINE[stars.north],
      main: NORTH_DIALOG[stars.north],
    },
    middle: {
      label: '中キャラ',
      star: stars.center,
      starHeadline: STAR_HEADLINE[stars.center],
      main: CENTER_DIALOG[stars.center],
    },
    inner: {
      label: '裏キャラ',
      star: stars.east,
      starHeadline: STAR_HEADLINE[stars.east],
      main: EAST_DIALOG[stars.east],
    },
    luckyColor: LUCKY_COLOR_BY_DAY_STEM[sanchu.day.stem],
    bucchakeLevel: BUCCHAKE_BY_EAST_STAR[stars.east],
    sanchu, stars,
  }
}
